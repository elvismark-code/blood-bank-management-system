    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        if (jComboBoxDonor.getSelectedItem() == null || jComboBoxBank.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Please make sure you have Donors and Banks in the system.");
            return;
        }

        String dateStr = txtDate.getText().trim();
        String status = (String) jComboBoxStatus.getSelectedItem();
        
        // Extract IDs from ComboBox (format "ID - Name")
        String donorItem = (String) jComboBoxDonor.getSelectedItem();
        int donorId = Integer.parseInt(donorItem.split(" - ")[0]);
        
        String bankItem = (String) jComboBoxBank.getSelectedItem();
        int bankId = Integer.parseInt(bankItem.split(" - ")[0]);

        if (dateStr.equals("yyyy-mm-dd hh:mm:ss") || dateStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter a valid Date and Time (yyyy-mm-dd hh:mm:ss).");
            return;
        }

        String sql = "INSERT INTO appointment (donor_id, bank_id, appointment_date, status) VALUES (?, ?, ?, ?)";
        
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            
            ps.setInt(1, donorId);
            ps.setInt(2, bankId);
            ps.setString(3, dateStr);
            ps.setString(4, status);

            if (ps.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Appointment added successfully!");
                loadData();
                clearFields();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnAddActionPerformed

