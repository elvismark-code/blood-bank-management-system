    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow == -1) return;

        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        
        txtAppointmentId.setText(model.getValueAt(selectedRow, 0).toString());
        
        // We need to find the full ComboBox item that contains the donor name
        String donorName = model.getValueAt(selectedRow, 1).toString();
        for (int i = 0; i < jComboBoxDonor.getItemCount(); i++) {
            if (jComboBoxDonor.getItemAt(i).contains(donorName)) {
                jComboBoxDonor.setSelectedIndex(i);
                break;
            }
        }
        
        // Do the same for Bank
        String bankName = model.getValueAt(selectedRow, 2).toString();
        for (int i = 0; i < jComboBoxBank.getItemCount(); i++) {
            if (jComboBoxBank.getItemAt(i).contains(bankName)) {
                jComboBoxBank.setSelectedIndex(i);
                break;
            }
        }
        
        Object dateObj = model.getValueAt(selectedRow, 3);
        txtDate.setText(dateObj != null ? dateObj.toString() : "");
        
        jComboBoxStatus.setSelectedItem(model.getValueAt(selectedRow, 4).toString());
    }//GEN-LAST:event_jTable1MouseClicked

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        String idStr = txtAppointmentId.getText().trim();
        if (idStr.equals("auto") || idStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an appointment from the table.");
            return;
        }

        int appointmentId = Integer.parseInt(idStr);
        String dateStr = txtDate.getText().trim();
        String status = (String) jComboBoxStatus.getSelectedItem();
        
        String donorItem = (String) jComboBoxDonor.getSelectedItem();
        int donorId = Integer.parseInt(donorItem.split(" - ")[0]);
        
        String bankItem = (String) jComboBoxBank.getSelectedItem();
        int bankId = Integer.parseInt(bankItem.split(" - ")[0]);

        String sql = "UPDATE appointment SET donor_id=?, bank_id=?, appointment_date=?, status=? WHERE appointment_id=?";
        
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            
            ps.setInt(1, donorId);
            ps.setInt(2, bankId);
            ps.setString(3, dateStr);
            ps.setString(4, status);
            ps.setInt(5, appointmentId);

            if (ps.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Appointment updated successfully!");
                loadData();
                clearFields();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        String idStr = txtAppointmentId.getText().trim();
        if (idStr.equals("auto") || idStr.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select an appointment.");
            return;
        }

        int confirm = JOptionPane.showConfirmDialog(this, 
                "Delete this appointment?", "Confirm", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) return;

        int appointmentId = Integer.parseInt(idStr);
        String sql = "DELETE FROM appointment WHERE appointment_id = ?";
        
        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            
            ps.setInt(1, appointmentId);
            
            if (ps.executeUpdate() > 0) {
                JOptionPane.showMessageDialog(this, "Appointment deleted successfully!");
                loadData();
                clearFields();
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Cannot delete. Error: " + e.getMessage());
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String keyword = txtSearch.getText().trim();
        if (keyword.isEmpty()) {
            loadData();
            return;
        }

        String sql = "SELECT a.appointment_id, CONCAT(d.first_name, ' ', d.last_name) AS donor_name, "
                   + "b.bank_name, a.appointment_date, a.status "
                   + "FROM appointment a "
                   + "JOIN donor d ON a.donor_id = d.donor_id "
                   + "JOIN blood_bank b ON a.bank_id = b.bank_id "
                   + "WHERE d.first_name LIKE ? OR d.last_name LIKE ? OR b.bank_name LIKE ?";
        
        String[] cols = {"ID", "Donor", "Bank", "Date and Time", "Status"};
        DefaultTableModel model = new DefaultTableModel(cols, 0) {
            @Override
            public boolean isCellEditable(int row, int column) { return false; }
        };

        try (Connection con = DBConnection.getConnection();
             PreparedStatement ps = con.prepareStatement(sql)) {
            
            ps.setString(1, "%" + keyword + "%");
            ps.setString(2, "%" + keyword + "%");
            ps.setString(3, "%" + keyword + "%");
            
            ResultSet rs = ps.executeQuery();
            while (rs.next()) {
                Vector<Object> row = new Vector<>();
                for (int i = 1; i <= cols.length; i++) {
                    row.add(rs.getObject(i));
                }
                model.addRow(row);
            }
            jTable1.setModel(model);
            
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnSearchActionPerformed

